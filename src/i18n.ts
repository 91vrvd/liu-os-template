export type TranslationKey = keyof typeof translations.zh;

const languageChangeEvent = 'liu-os-language-change';

export const getStoredLanguage = (): Language => {
  if (typeof window === 'undefined') return 'zh';
  return localStorage.getItem(LANGUAGE_STORAGE_KEY) === 'en' ? 'en' : 'zh';
};

export const translate = (key: TranslationKey, language = getStoredLanguage()) => {
  return translations[language][key] ?? translations.zh[key] ?? key;
};

export const applyI18nToDom = (language: Language) => {
  if (typeof document === 'undefined') return;

  document.documentElement.lang = language === 'zh' ? 'zh-CN' : 'en';
  document.body.dataset.language = language;
  document.querySelectorAll<HTMLElement>('[data-i18n]').forEach((element) => {
    const key = element.dataset.i18n as TranslationKey | undefined;
    if (key && translations[language][key]) {
      element.textContent = translations[language][key];
    }
  });
};

export const setStoredLanguage = (language: Language) => {
  if (typeof window === 'undefined') return;

  localStorage.setItem(LANGUAGE_STORAGE_KEY, language);
  applyI18nToDom(language);
  window.dispatchEvent(new CustomEvent<Language>(languageChangeEvent, { detail: language }));
};

export const useI18n = () => {
  const [language, setLanguage] = useState<Language>(getStoredLanguage);

  useEffect(() => {
    applyI18nToDom(language);

    const handleLanguageChange = (event: Event) => {
      setLanguage((event as CustomEvent<Language>).detail ?? getStoredLanguage());
    };

    window.addEventListener(languageChangeEvent, handleLanguageChange);
    return () => window.removeEventListener(languageChangeEvent, handleLanguageChange);
  }, [language]);

  return {
    language,
    setLanguage: setStoredLanguage,
    t: (key: TranslationKey) => translate(key, language),
  };
};

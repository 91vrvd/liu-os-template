import fs from 'node:fs/promises';
import path from 'node:path';

const root = process.cwd();
const catalogPath = path.join(root, 'src/data/aiBotCatalog.ts');
const reportPath = path.join(root, 'reports/ai-bookmark-sync.json');
const aiBotHost = 'ai-bot.cn';
const trackingParams = /^(utm_.*|ref|from|source|channel|campaign|invite|affiliate|aff|fbclid|gclid|si)$/i;
const excludedHosts = /^(?:www\.)?(?:bing|google)\.(?:com|cn)$/i;

const readCatalog = async () => {
  const source = await fs.readFile(catalogPath, 'utf8');
  const start = source.indexOf(' = [') + 3;
  const end = source.lastIndexOf(']') + 1;
  if (start < 3 || end <= start) throw new Error('catalog-array-not-found');
  return JSON.parse(source.slice(start, end).replace(/,\s*]$/, ']'));
};

const normalizeUrl = (value, baseUrl) => {
  try {
    const url = new URL(value, baseUrl);
    if (!['http:', 'https:'].includes(url.protocol)) return null;
    for (const key of [...url.searchParams.keys()]) {
      if (trackingParams.test(key)) url.searchParams.delete(key);
    }
    url.hash = '';
    return url.href;
  } catch {
    return null;
  }
};

const isAiBotUrl = (value) => {
  try {
    return new URL(value).hostname.toLowerCase() === aiBotHost;
  } catch {
    return true;
  }
};

const stripMarkup = (value) => value.replace(/<[^>]+>/g, ' ').replace(/\s+/g, ' ').trim();

const extractCandidateLinks = (html, sourceUrl) => {
  const candidates = [];
  const anchorPattern = /<a\b([^>]*)>([\s\S]*?)<\/a>/gi;
  let match;
  while ((match = anchorPattern.exec(html))) {
    const attrs = match[1];
    const href = attrs.match(/\bhref\s*=\s*['"]([^'"]+)['"]/i)?.[1];
    if (!href) continue;
    const targetUrl = normalizeUrl(href, sourceUrl);
    if (!targetUrl || isAiBotUrl(targetUrl)) continue;
    const host = new URL(targetUrl).hostname;
    if (excludedHosts.test(host) || /(?:wp-content|googleads|doubleclick|beian)/i.test(targetUrl)) continue;
    const text = stripMarkup(match[2]);
    const context = `${attrs} ${text} ${html.slice(Math.max(0, match.index - 240), match.index + match[0].length + 240)}`;
    let score = 0;
    if (/官网|官方网站|产品官网|访问|立即使用|official|website|visit|get started/i.test(context)) score += 8;
    if (/target\s*=\s*['"]_blank['"]/i.test(attrs)) score += 2;
    if (/external|site-go|site-go-url/i.test(attrs)) score += 3;
    if (/广告|赞助|sponsored|banner/i.test(context)) score -= 8;
    candidates.push({ targetUrl, score, text });
  }
  return candidates.sort((a, b) => b.score - a.score);
};

const resolveInternalPage = async (sourcePageUrl) => {
  try {
    const response = await fetch(sourcePageUrl, {
      headers: { 'user-agent': 'desktop-template-bookmark-sync/1.0' },
      signal: AbortSignal.timeout(15000),
    });
    if (!response.ok) return null;
    const html = await response.text();
    const candidates = extractCandidateLinks(html, sourcePageUrl);
    const best = candidates.find((candidate) => candidate.score >= 8);
    return best?.targetUrl ?? null;
  } catch {
    return null;
  }
};

const writeCatalog = async (bookmarks) => {
  const output = `import type { SafariBookmark } from './aiBookmarks';\n\n// Generated by scripts/sync-ai-bookmarks.mjs. Do not edit by hand.\nexport const aiBotCatalog: SafariBookmark[] = ${JSON.stringify(bookmarks, null, 2)};\n`;
  await fs.writeFile(catalogPath, output);
};

const main = async () => {
  const original = await readCatalog();
  const resolve = process.argv.includes('--resolve');
  const report = {
    generatedAt: new Date().toISOString(),
    source: 'https://ai-bot.cn/',
    totalInput: original.length,
    resolved: 0,
    unresolved: 0,
    filtered: 0,
    duplicateTargetsRemoved: 0,
    unresolvedEntries: [],
  };
  const seenTargets = new Set();
  const output = [];
  const resolvedInternal = new Map();

  if (resolve) {
    const internalEntries = original.filter((entry) => isAiBotUrl(entry.url));
    for (let index = 0; index < internalEntries.length; index += 8) {
      const batch = internalEntries.slice(index, index + 8);
      const results = await Promise.all(batch.map(async (entry) => [entry.id, await resolveInternalPage(entry.url)]));
      results.forEach(([id, targetUrl]) => resolvedInternal.set(id, targetUrl));
    }
  }

  for (const entry of original) {
    const sourcePageUrl = isAiBotUrl(entry.url) ? normalizeUrl(entry.url) : undefined;
    let targetUrl = sourcePageUrl ? (resolvedInternal.get(entry.id) ?? null) : normalizeUrl(entry.url);

    if (targetUrl && isAiBotUrl(targetUrl)) targetUrl = null;
    if (targetUrl) {
      if (seenTargets.has(targetUrl)) {
        report.duplicateTargetsRemoved += 1;
        continue;
      }
      seenTargets.add(targetUrl);
      report.resolved += 1;
    } else {
      report.unresolved += 1;
      report.unresolvedEntries.push({ id: entry.id, title: entry.title, sourcePageUrl: sourcePageUrl ?? entry.url });
    }

    output.push({
      id: entry.id,
      title: entry.title,
      targetUrl: targetUrl ?? '',
      ...(sourcePageUrl ? { sourcePageUrl } : {}),
      descriptionZh: entry.descriptionZh,
      descriptionEn: entry.descriptionEn,
      categoryId: entry.categoryId,
      ...(entry.subcategoryId ? { subcategoryId: entry.subcategoryId } : {}),
      ...(targetUrl ? { icon: `https://www.google.com/s2/favicons?domain=${new URL(targetUrl).hostname}&sz=64` } : {}),
      status: targetUrl ? 'resolved' : 'unresolved',
    });
  }

  await fs.mkdir(path.dirname(reportPath), { recursive: true });
  await writeCatalog(output);
  await fs.writeFile(reportPath, `${JSON.stringify(report, null, 2)}\n`);
  console.log(JSON.stringify({ ...report, unresolvedEntries: report.unresolvedEntries.length }, null, 2));
};

main().catch((error) => {
  console.error(error);
  process.exitCode = 1;
});
